import {
  useDeletePlatformMutation,
  usePlatformsQuery,
  useSavePlatformMutation,
  useSetPlatformStatusMutation,
} from "@/store/api";
import type { Platform } from "@/store/types";

/** Create / rename: only the name is asked; the id is generated by the server. */
function PlatformDialog({
  platform,
  onClose,
}: {
  platform: Platform | null;
  onClose: () => void;
}) {
  const t = useT();
  const [save, { isLoading }] = useSavePlatformMutation();
  const [name, setName] = useState(platform?.name ?? "");
  const [error, setError] = useState<TranslationKey | null>(null);
  const [invite, setInvite] = useState<string | null>(null);

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!name.trim()) return setError("validation.required");
    try {
      const { account } = await save({
        id: platform?.id,
        name: name.trim(),
      }).unwrap();
      toast.success(t(platform ? "platforms.updated" : "platforms.created"));
      // a new platform comes with its manager account: show its invite once
      if (account)
        setInvite(
          inviteMessage(t, account.username, account.temporaryPassword),
        );
      else onClose();
    } catch {
      // the API error middleware shows the error
    }
  };

  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent>
        {invite ? (
          <InviteView
            title={t("platforms.created")}
            description={t("platforms.accountCreated")}
            message={invite}
            onDone={onClose}
          />
        ) : (
          <form noValidate onSubmit={submit} className="grid gap-4">
            <DialogHeader>
              <DialogTitle>
                {t(platform ? "platforms.editTitle" : "platforms.newTitle")}
              </DialogTitle>
              <DialogDescription>
                {t(
                  platform
                    ? "platforms.editDescription"
                    : "platforms.newDescription",
                )}
              </DialogDescription>
            </DialogHeader>
            {error && (
              <Alert variant="destructive">
                <AlertDescription>{t(error)}</AlertDescription>
              </Alert>
            )}
            <div className="grid gap-2">
              <Label htmlFor="platformName">{t("platforms.name")}</Label>
              <Input
                id="platformName"
                autoFocus
                maxLength={80}
                placeholder={t("platforms.namePlaceholder")}
                value={name}
                onChange={(e) => setName(e.target.value)}
              />
            </div>
            <DialogFooter>
              <Button type="button" variant="outline" onClick={onClose}>
                {t("common.cancel")}
              </Button>
              <Button type="submit" disabled={isLoading || !name.trim()}>
                {isLoading && <Loader2 className="animate-spin" />}
                {t(platform ? "common.save" : "common.create")}
              </Button>
            </DialogFooter>
          </form>
        )}
      </DialogContent>
    </Dialog>
  );
}

function CopyId({ id }: { id: string }) {
  const t = useT();
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(id);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error(t("managers.copyFailed"));
    }
  };
  return (
    <button
      type="button"
      onClick={copy}
      title={id}
      className="inline-flex items-center gap-1.5 rounded bg-muted px-1.5 py-0.5 font-mono text-[11px] text-muted-foreground hover:text-foreground"
    >
      {id.slice(0, 8)}…
      {copied ? <Check className="size-3" /> : <Copy className="size-3" />}
    </button>
  );
}

export default function PlatformsPage() {
  const t = useT();
  const { locale } = useLocale();
  const { me, isSuperAdmin, can } = useAccess();
  const { data: platforms, isLoading } = usePlatformsQuery();
  const [remove, { isLoading: deleting }] = useDeletePlatformMutation();
  const [setStatus] = useSetPlatformStatusMutation();
  // `editing` undefined = closed, null = new platform
  const [editing, setEditing] = useState<Platform | null | undefined>(
    undefined,
  );
  const [toDelete, setToDelete] = useState<Platform | null>(null);
  const canEdit = can("platforms.update");
  const canCreate = can("platforms.create");
  // non super admins can't delete the platform they're working in (the API enforces it too)
  const canDelete = (p: Platform) =>
    can("platforms.delete") && (isSuperAdmin || p.id !== me?.platform_id);

  const confirmDelete = async () => {
    if (!toDelete) return;
    try {
      await remove(toDelete.id).unwrap();
      toast.success(t("platforms.deleted"));
      setToDelete(null);
    } catch {
      // the API error middleware shows the error
    }
  };

  return (
    <div className="mx-auto grid max-w-6xl gap-6">
      <PageHeader
        title={t("platforms.title")}
        description={t("platforms.pageDescription")}
      >
        {canCreate && (
          <Button onClick={() => setEditing(null)}>
            <Plus /> {t("platforms.new")}
          </Button>
        )}
      </PageHeader>

      <Card>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>{t("platforms.name")}</TableHead>
                <TableHead>ID</TableHead>
                <TableHead className="text-right">
                  {t("platforms.members")}
                </TableHead>
                <TableHead className="hidden text-right md:table-cell">
                  {t("platforms.roles")}
                </TableHead>
                <TableHead className="hidden md:table-cell">
                  {t("platforms.createdAt")}
                </TableHead>
                <TableHead>{t("status.title")}</TableHead>
                <TableHead className="w-12">
                  <span className="sr-only">{t("common.actions")}</span>
                </TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {isLoading && (
                <TableRow>
                  <TableCell colSpan={7}>
                    <Skeleton className="h-6" />
                  </TableCell>
                </TableRow>
              )}
              {platforms?.length === 0 && (
                <TableRow>
                  <TableCell colSpan={7} className="py-12 text-center">
                    <Building2 className="mx-auto mb-2 size-6 text-muted-foreground" />
                    <p className="font-medium">{t("platforms.emptyTitle")}</p>
                    <p className="text-sm text-muted-foreground">
                      {t("platforms.emptyText")}
                    </p>
                  </TableCell>
                </TableRow>
              )}
              {platforms?.map((p) => (
                <TableRow key={p.id}>
                  <TableCell>
                    <div className="flex items-center gap-2 font-medium">
                      <span className="flex size-7 items-center justify-center rounded-md bg-primary/10 text-primary">
                        <Building2 className="size-3.5" />
                      </span>
                      {p.name}
                      {p.id === me?.platform_id && (
                        <Badge variant="secondary">
                          {t("platforms.current")}
                        </Badge>
                      )}
                    </div>
                  </TableCell>
                  <TableCell>
                    <CopyId id={p.id} />
                  </TableCell>
                  <TableCell className="text-right tabular-nums">
                    {p.member_count}
                  </TableCell>
                  <TableCell className="hidden text-right tabular-nums md:table-cell">
                    {p.role_count}
                  </TableCell>
                  <TableCell className="hidden text-sm md:table-cell">
                    {formatDateTime(p.created_at, locale, "—")}
                  </TableCell>
                  <TableCell>
                    <StatusSwitch
                      active={p.is_active}
                      onChange={(isActive) =>
                        setStatus({ id: p.id, isActive }).unwrap()
                      }
                      disabledReason={
                        !can("platforms.updateStatus")
                          ? t("status.noPermission")
                          : !isSuperAdmin && p.id === me?.platform_id
                            ? t("errors.ACTIVE_PLATFORM")
                            : null
                      }
                    />
                  </TableCell>
                  <TableCell>
                    {(canEdit || canDelete(p)) && (
                      <DropdownMenu>
                        <DropdownMenuTrigger
                          render={
                            <Button
                              variant="ghost"
                              size="icon"
                              aria-label={t("common.actions")}
                            />
                          }
                        >
                          <MoreHorizontal />
                        </DropdownMenuTrigger>
                        <DropdownMenuContent align="end">
                          {canEdit && (
                            <DropdownMenuItem onClick={() => setEditing(p)}>
                              <Pencil /> {t("platforms.rename")}
                            </DropdownMenuItem>
                          )}
                          {canDelete(p) && (
                            <>
                              {canEdit && <DropdownMenuSeparator />}
                              <DropdownMenuItem
                                variant="destructive"
                                onClick={() => setToDelete(p)}
                              >
                                <Trash2 /> {t("common.delete")}
                              </DropdownMenuItem>
                            </>
                          )}
                        </DropdownMenuContent>
                      </DropdownMenu>
                    )}
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      {editing !== undefined && (
        <PlatformDialog
          key={editing?.id ?? "new"}
          platform={editing}
          onClose={() => setEditing(undefined)}
        />
      )}
      <ConfirmDialog
        open={!!toDelete}
        title={t("platforms.deleteTitle", { name: toDelete?.name ?? "" })}
        description={t("platforms.deleteDescription")}
        confirmLabel={t("common.delete")}
        loading={deleting}
        onConfirm={confirmDelete}
        onClose={() => setToDelete(null)}
      />
    </div>
  );
}
