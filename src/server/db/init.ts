/**
 * An app's customers and their orders — every row carries platform_id + app_id, and
 * composite foreign keys keep them consistent (a device or order always belongs to a user
 * of the same app, and the app to the same platform).
 *
 *   app_users ─┬─ devices
 *              └─ orders ── order_items
 *
 * Digital goods only, no product catalog: an order lists its items (name, qty, price) and
 * says what paying it gives — the billing:
 *   lifetime    one-time payment, never expires          (no interval)
 *   fixed_term  one-time payment, access for N units      (interval_unit + interval_count)
 *   recurring   subscription, renews every N units        (interval_unit + interval_count)
 * Two statuses: payment_status (pending / paid / failed / refunded) and order_status
 * (pending / active / expired / cancelled; active needs paid). Activating sets the access
 * period (starts_at / ends_at; ends_at NULL = lifetime).
 * Money is stored in minor units (cents); the total is the sum of the items, never stored.
 */
async function migrateCommerce() {
  // lets other tables reference (app, platform) / (row, app) pairs
  await query(
    `CREATE UNIQUE INDEX IF NOT EXISTS apps_id_platform_idx ON apps (id, platform_id)`,
  );

  await query(`
    CREATE TABLE IF NOT EXISTS app_users (
      id           SERIAL PRIMARY KEY,
      platform_id  UUID         NOT NULL,
      app_id       INT          NOT NULL,
      name           VARCHAR(120) NOT NULL,
      email          VARCHAR(255),
      phone          VARCHAR(16),  -- E.164, e.g. +94771234567
      phone_country  CHAR(2),      -- ISO country it was entered for (+1 is shared)
      is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
      created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
      updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
      FOREIGN KEY (app_id, platform_id) REFERENCES apps (id, platform_id) ON DELETE CASCADE,
      UNIQUE (id, app_id)
    );
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS app_users_platform_idx ON app_users (platform_id, app_id)`,
  );
  await query(
    `CREATE UNIQUE INDEX IF NOT EXISTS app_users_email_idx ON app_users (app_id, LOWER(email)) WHERE email IS NOT NULL`,
  );
  // how many active devices a user may have
  await query(
    `ALTER TABLE app_users ADD COLUMN IF NOT EXISTS max_devices SMALLINT NOT NULL DEFAULT 1 CHECK (max_devices BETWEEN 1 AND 1000)`,
  );
  // how many orders a user may have waiting for payment (pending) at once
  await query(
    `ALTER TABLE app_users ADD COLUMN IF NOT EXISTS max_pending_orders SMALLINT NOT NULL DEFAULT 3 CHECK (max_pending_orders BETWEEN 1 AND 100)`,
  );
  // a user needs an email or a phone (NOT VALID: older rows without either are kept)
  const { rowCount: contactCheck } = await query(
    `SELECT 1 FROM pg_constraint WHERE conname = 'app_users_contact_check'`,
  );
  if (!contactCheck) {
    await query(
      `ALTER TABLE app_users ADD CONSTRAINT app_users_contact_check CHECK (email IS NOT NULL OR phone IS NOT NULL) NOT VALID`,
    );
  }
  // external IDs were dropped; phones became E.164 + country
  await query(`ALTER TABLE app_users DROP COLUMN IF EXISTS external_id`);
  await query(`ALTER TABLE app_users ALTER COLUMN phone TYPE VARCHAR(16)`);
  await query(
    `ALTER TABLE app_users ADD COLUMN IF NOT EXISTS phone_country CHAR(2)`,
  );
  const { rowCount: phoneCheck } = await query(
    `SELECT 1 FROM pg_constraint WHERE conname = 'app_users_phone_country_check'`,
  );
  if (!phoneCheck) {
    await query(
      `UPDATE app_users SET phone = NULL, phone_country = NULL
        WHERE phone IS NULL OR phone_country IS NULL OR phone !~ '^\\+[1-9][0-9]{6,14}$'`,
    );
    await query(`
      ALTER TABLE app_users ADD CONSTRAINT app_users_phone_country_check
        CHECK ((phone IS NULL) = (phone_country IS NULL) AND (phone IS NULL OR phone ~ '^\\+[1-9][0-9]{6,14}$'))
    `);
  }

  await query(`
    CREATE TABLE IF NOT EXISTS devices (
      id           SERIAL PRIMARY KEY,
      platform_id  UUID         NOT NULL,
      app_id       INT          NOT NULL,
      app_user_id  INT,
      device_uid   VARCHAR(191) NOT NULL,
      os           VARCHAR(10)  NOT NULL CHECK (os IN ('android', 'ios', 'web', 'windows', 'macos', 'linux', 'other')),
      model        VARCHAR(120),
      is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
      created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
      updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
      FOREIGN KEY (app_id, platform_id) REFERENCES apps (id, platform_id) ON DELETE CASCADE,
      FOREIGN KEY (app_user_id, app_id) REFERENCES app_users (id, app_id) ON DELETE SET NULL (app_user_id),
      UNIQUE (app_id, device_uid)
    );
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS devices_platform_idx ON devices (platform_id, app_id)`,
  );
  // what the app computes from the hardware / browser; not unique (it can change or repeat)
  await query(
    `ALTER TABLE devices ADD COLUMN IF NOT EXISTS fingerprint VARCHAR(255)`,
  );
  await query(
    `CREATE INDEX IF NOT EXISTS devices_fingerprint_idx ON devices (app_id, fingerprint) WHERE fingerprint IS NOT NULL`,
  );

  // the first version had a product catalog and a subscriptions table: replaced by orders
  // that carry their own billing (only ever held test data)
  const { rowCount: oldCatalog } = await query(
    `SELECT 1 FROM information_schema.tables WHERE table_name = 'plans'`,
  );
  if (oldCatalog)
    await query(
      `DROP TABLE IF EXISTS subscriptions, order_items, orders, plans, products CASCADE`,
    );
  // then one `status` became payment_status + order_status (only ever held test data)
  const { rowCount: oldStatus } = await query(
    `SELECT 1 FROM information_schema.columns WHERE table_name = 'orders' AND column_name = 'status'`,
  );
  if (oldStatus)
    await query(`DROP TABLE IF EXISTS order_items, orders CASCADE`);

  await query(`
    CREATE TABLE IF NOT EXISTS orders (
      id              SERIAL PRIMARY KEY,
      platform_id     UUID         NOT NULL,
      app_id          INT          NOT NULL,
      app_user_id     INT          NOT NULL,
      order_number    VARCHAR(24)  NOT NULL UNIQUE,
      payment_status  VARCHAR(10)  NOT NULL DEFAULT 'pending'
                                   CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded')),
      order_status    VARCHAR(10)  NOT NULL DEFAULT 'pending'
                                   CHECK (order_status IN ('pending', 'active', 'expired', 'cancelled')),
      currency        VARCHAR(10)  NOT NULL,
      billing         VARCHAR(10)  NOT NULL CHECK (billing IN ('lifetime', 'fixed_term', 'recurring')),
      interval_unit   VARCHAR(5)   CHECK (interval_unit IN ('day', 'week', 'month', 'year')),
      interval_count  SMALLINT     CHECK (interval_count BETWEEN 1 AND 365),
      starts_at       TIMESTAMPTZ,
      ends_at         TIMESTAMPTZ,
      note            VARCHAR(500),
      paid_at         TIMESTAMPTZ,
      created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
      updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
      FOREIGN KEY (app_id, platform_id) REFERENCES apps (id, platform_id) ON DELETE CASCADE,
      FOREIGN KEY (app_user_id, app_id) REFERENCES app_users (id, app_id),
      CHECK ((billing = 'lifetime') = (interval_unit IS NULL AND interval_count IS NULL)),
      CHECK ((interval_unit IS NULL) = (interval_count IS NULL)),
      CHECK (ends_at IS NULL OR ends_at >= starts_at),
      -- only paid orders give access (a subscription stays active while a renewal is retried)
      CONSTRAINT orders_active_paid_check CHECK (order_status <> 'active' OR paid_at IS NOT NULL)
    );
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS orders_platform_idx ON orders (platform_id, app_id, created_at DESC)`,
  );
  await query(
    `CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (app_user_id)`,
  );

  await query(`
    CREATE TABLE IF NOT EXISTS order_items (
      id           SERIAL PRIMARY KEY,
      order_id     INT          NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
      name         VARCHAR(160) NOT NULL,
      quantity     INT          NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 1000),
      unit_amount  BIGINT       NOT NULL CHECK (unit_amount >= 0)
    );
  `);
  // orders had an on / off switch: dropped, the order status covers it (cancelled / active)
  await query(`ALTER TABLE orders DROP COLUMN IF EXISTS is_active`);
  await query(`ALTER TABLE orders ALTER COLUMN currency TYPE VARCHAR(10)`);
  await query(`DELETE FROM permissions WHERE key = 'order-active'`);
  await query(
    `CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items (order_id)`,
  );
}

/**
 * Online payments through Stripe — one Stripe account for every platform (keys in the
 * environment); each order knows its platform:
 *
 *   orders            + the open payment link (a Checkout Session, or a subscription's
 *                       unpaid invoice) and the Stripe customer / subscription
 *   payments          every payment attempt Stripe reported (succeeded, failed, refunded…)
 *   stripe_events     webhook events already handled (Stripe can deliver one twice)
 */
async function migratePayments() {
  // Stripe keys were per platform for a short while: now they come from the environment
  await query(`DROP TABLE IF EXISTS platform_stripe`);
  await query(`DELETE FROM permissions WHERE key = 'stripe-settings'`);

  // a subscription stays active while Stripe retries a failed renewal: "active" now needs an
  // order that was paid (paid_at), not a payment status of paid
  const { rows: oldCheck } = await query<{ conname: string }>(
    `SELECT conname FROM pg_constraint
      WHERE conrelid = 'orders'::regclass AND contype = 'c'
        AND pg_get_constraintdef(oid) LIKE '%order_status)::text <> ''active''::text) OR ((payment_status%'`,
  );
  for (const c of oldCheck)
    await query(`ALTER TABLE orders DROP CONSTRAINT "${c.conname}"`);
  const { rowCount: newCheck } = await query(
    `SELECT 1 FROM pg_constraint WHERE conname = 'orders_active_paid_check'`,
  );
  if (!newCheck) {
    await query(
      `ALTER TABLE orders ADD CONSTRAINT orders_active_paid_check CHECK (order_status <> 'active' OR paid_at IS NOT NULL)`,
    );
  }
  await query(`
    ALTER TABLE orders
      ADD COLUMN IF NOT EXISTS checkout_session_id     VARCHAR(255),
      ADD COLUMN IF NOT EXISTS pay_url                 TEXT,
      ADD COLUMN IF NOT EXISTS pay_url_expires_at      TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS stripe_customer_id      VARCHAR(255),
      ADD COLUMN IF NOT EXISTS stripe_subscription_id  VARCHAR(255)
  `);
  await query(
    `CREATE UNIQUE INDEX IF NOT EXISTS orders_stripe_subscription_idx ON orders (stripe_subscription_id) WHERE stripe_subscription_id IS NOT NULL`,
  );
  await query(
    `CREATE INDEX IF NOT EXISTS orders_checkout_session_idx ON orders (checkout_session_id) WHERE checkout_session_id IS NOT NULL`,
  );

  await query(`
    CREATE TABLE IF NOT EXISTS payments (
      id               SERIAL PRIMARY KEY,
      platform_id      UUID         NOT NULL,
      app_id           INT          NOT NULL,
      order_id         INT          NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
      provider         VARCHAR(20)  NOT NULL DEFAULT 'stripe',
      reference        VARCHAR(255) NOT NULL,  -- Stripe PaymentIntent (or the invoice when it has none)
      kind             VARCHAR(10)  NOT NULL CHECK (kind IN ('checkout', 'renewal')),
      invoice_id       VARCHAR(255),
      status           VARCHAR(20)  NOT NULL
                                    CHECK (status IN ('processing', 'succeeded', 'failed', 'refunded', 'partially_refunded')),
      amount           BIGINT       NOT NULL CHECK (amount >= 0),
      amount_refunded  BIGINT       NOT NULL DEFAULT 0 CHECK (amount_refunded >= 0),
      currency         VARCHAR(10)  NOT NULL,
      method_type      VARCHAR(40),            -- card, link, klarna, us_bank_account…
      method_details   JSONB,                  -- brand, last4, wallet, bank…
      receipt_url      TEXT,
      failure_message  VARCHAR(500),
      livemode         BOOLEAN      NOT NULL DEFAULT FALSE,
      paid_at          TIMESTAMPTZ,
      created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
      updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
      FOREIGN KEY (app_id, platform_id) REFERENCES apps (id, platform_id) ON DELETE CASCADE,
      UNIQUE (provider, reference)
    );
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS payments_platform_idx ON payments (platform_id, app_id, created_at DESC)`,
  );
  await query(
    `CREATE INDEX IF NOT EXISTS payments_order_idx ON payments (order_id)`,
  );
  await query(`ALTER TABLE payments ALTER COLUMN currency TYPE VARCHAR(10)`);

  await query(`
    CREATE TABLE IF NOT EXISTS stripe_events (
      id           VARCHAR(255) PRIMARY KEY,
      type         VARCHAR(100) NOT NULL,
      received_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
    );
  `);
  await query(`ALTER TABLE stripe_events DROP COLUMN IF EXISTS platform_id`);
}

