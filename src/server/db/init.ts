// Bump when migrate() changes so a hot-reloaded dev server re-runs it.
const SCHEMA_VERSION = 43;

const globalForInit = globalThis as unknown as {
  dbReady?: Promise<void>;
  dbVersion?: number;
};

/** Runs schema setup + seed once per process; every API handler awaits this. */
export function ensureDb() {
  if (globalForInit.dbVersion !== SCHEMA_VERSION)
    globalForInit.dbReady = undefined;
  globalForInit.dbVersion = SCHEMA_VERSION;
  globalForInit.dbReady ??= (async () => {
    await migrate();
    await seedSuperAdminRole(); // the role first, then the super admin account that uses it
    await seedDefaultAdmin();
    await seedFirstRun();
    await patchManagersApi();
    await patchPlatformsCard();
    await patchStatusCards();
    await addSeedCards("patch.own-platform-card", ["platform-own-update"]);
    await addSeedCards("patch.apps-card", ["apps"]);
    await addSeedCards("patch.app-credentials-card", ["app-credentials"]);
    await addSeedCards("patch.app-config-card", ["app-config"]);
    await addSeedCards("patch.commerce-cards", ["users", "devices", "orders"]);
    await patchDirectOrders();
    await patchCommerceStatusCards();
    await patchUserDeviceLimitCard();
    await addSeedCards("patch.payment-cards", ["payments"]);
    await patchOrderCheckoutCard();
    await patchUserPendingLimitCard();
    await patchOrderTemplateCards();
    await seedSuperAdminRole(); // Super Admin also gets the cards/actions created above
  })().catch((err) => {
    globalForInit.dbReady = undefined; // retry on the next request
    throw err;
  });
  return globalForInit.dbReady;
}
